"""Work the power-station sizing cases independently of lib/power.ts.

This is the "by hand" reference for tests/power.test.ts. It reads only
data/bluetti/stations.json and applies the PRD F4 formulas written out below.
It does not import or call the app code, so a bug in lib/power.ts cannot
also hide here.

Writes docs/evidence/calculator-cases.md with the arithmetic for every case.

Run: python scripts/calc_cases.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STATIONS = json.loads((ROOT / "data" / "bluetti" / "stations.json").read_text(encoding="utf-8"))
OUT = ROOT / "docs" / "evidence" / "calculator-cases.md"

DOD = 0.90
INVERTER = 0.85
HEADROOM = 1.2


def r2(x):
    return round(x + 1e-9, 2)


def evaluate(loads, s):
    """Return (row dict, arithmetic lines) for one station."""
    load_w = sum(l["running_w"] * l["qty"] for l in loads)
    running = load_w + s["self_consumption_w"]
    surging = [l for l in loads if l["surge_w"] is not None]
    if surging:
        a = max(surging, key=lambda l: l["surge_w"] - l["running_w"])
        peak = running - a["running_w"] + a["surge_w"]
    else:
        a, peak = None, running
    max_h = max(l["hours"] for l in loads)
    energy = sum(l["running_w"] * l["qty"] * l["hours"] for l in loads) + s["self_consumption_w"] * max_h
    usable = s["capacity_wh"] * DOD * INVERTER
    reasons = []
    if s["rated_w"] < running * HEADROOM:
        reasons.append(f"running {r2(running):g} W x 1.2 = {r2(running * HEADROOM):g} W > rated {s['rated_w']:g} W")
    if s["rated_w"] < peak:
        reasons.append(f"peak {r2(peak):g} W > rated {s['rated_w']:g} W")
    if usable < energy:
        reasons.append(f"usable {r2(usable):g} Wh < needed {r2(energy):g} Wh")
    row = {
        "code": s["code"], "model": s["model"], "price_php": s["price_php"],
        "running_w": r2(running), "peak_w": r2(peak), "energy_wh": r2(energy),
        "usable_wh": r2(usable), "runtime_h": r2(usable / running),
        "eligible": not reasons, "reasons": reasons,
    }
    return row


def recommend(loads):
    rows = [evaluate(loads, s) for s in STATIONS]
    eligible = [r for r in rows if r["eligible"]]
    # Price ascending, then larger margin rated_w - peak_w first.
    rated = {s["code"]: s["rated_w"] for s in STATIONS}
    eligible.sort(key=lambda r: (r["price_php"], -(rated[r["code"]] - r["peak_w"])))
    return eligible, [r for r in rows if not r["eligible"]]


def L(name, running_w, qty, hours, surge_w=None):
    return {"name": name, "running_w": running_w, "surge_w": surge_w, "qty": qty, "hours": hours}


# The 10 extra cases. Each one makes a different station the first eligible,
# so every station is the answer at least once.
CASES = [
    ("qty above 1", "Four 10 W LED bulbs for 7 h. Premium 30 V2 runs short on energy.",
     [L("LED bulb", 10, 4, 7)]),
    ("mixed hours", "A 10 W router for 12 h and a 60 W laptop for 4 h. Self-consumption runs for the longest load, 12 h.",
     [L("Router", 10, 1, 12), L("Laptop", 60, 1, 4)]),
    ("exactly at rated / 1.2", "238 W for 0.5 h. Premium 20: running 250 W, x 1.2 = 300 W = rated. Equal passes.",
     [L("Custom load", 238, 1, 0.5)]),
    ("one watt over rated / 1.2", "239 W for 0.5 h. Premium 20: running 251 W, x 1.2 = 301.2 W > 300 W. Rejected.",
     [L("Custom load", 239, 1, 0.5)]),
    ("microwave", "A 900 W microwave for 0.5 h. Premium 80 fails the 1.2 headroom.",
     [L("Microwave", 900, 1, 0.5)]),
    ("1 kW for an hour", "1000 W for 1 h. Premium 100 V2 has the power but not the energy.",
     [L("Custom load", 1000, 1, 1)]),
    ("1.2 kW for an hour", "1200 W for 1 h. Premium 150 has the power but not the energy.",
     [L("Custom load", 1200, 1, 1)]),
    ("2.1 kW, half an hour", "2100 W for 0.5 h. Premium 200 (AC200PL) fails the 1.2 headroom. Premium 200 V2 passes.",
     [L("Custom load", 2100, 1, 0.5)]),
    ("small load, long night", "150 W for 14 h. Only ELITE320 holds the energy.",
     [L("Custom load", 150, 1, 14)]),
    ("3 kW tool", "3000 W for 0.5 h. Only APEX300 has the power.",
     [L("Custom load", 3000, 1, 0.5)]),
]


def main():
    lines = [
        "# Calculator cases",
        "",
        "Generated by `python scripts/calc_cases.py`. Do not edit by hand.",
        "",
        "These are the 10 extra sizing cases for `tests/power.test.ts`. The script",
        "reads `data/bluetti/stations.json` and applies the PRD F4 formulas. It does",
        "not import `lib/power.ts`. The test expects the same numbers from the app code.",
        "",
        "Formulas: running = sum(W x qty) + self-consumption. peak = running - W(a) +",
        "surge(a), for the load `a` with the largest surge - running. energy = sum(W x",
        "qty x h) + self-consumption x max(h). usable = capacity x 0.90 x 0.85.",
        "Eligible when rated >= running x 1.2, rated >= peak and usable >= energy.",
        "runtime = usable / running. Eligible stations sort by price, then by",
        "rated - peak, largest first.",
        "",
    ]
    for i, (title, note, loads) in enumerate(CASES, 1):
        eligible, rejected = recommend(loads)
        lines += [f"## {i}. {title}", "", note, "", "Loads: " + "; ".join(
            f"{l['name']} {l['running_w']:g} W x {l['qty']} for {l['hours']:g} h" for l in loads), ""]
        first = eligible[0] if eligible else None
        if first:
            lines += [
                f"First eligible: **{first['code']} {first['model']}** (PHP {first['price_php']:,}).",
                f"running {first['running_w']:g} W, peak {first['peak_w']:g} W, energy {first['energy_wh']:g} Wh, "
                f"usable {first['usable_wh']:g} Wh, runtime {first['runtime_h']:g} h.",
                "",
            ]
        else:
            lines += ["No station is eligible.", ""]
        lines += ["Eligible order: " + (", ".join(r["code"] for r in eligible) or "none"), ""]
        lines += ["| Station | running W | peak W | energy Wh | usable Wh | Result |", "|---|---|---|---|---|---|"]
        for r in sorted(eligible + rejected, key=lambda r: r["price_php"]):
            res = "eligible" if r["eligible"] else "; ".join(r["reasons"])
            lines.append(f"| {r['code']} {r['model']} | {r['running_w']:g} | {r['peak_w']:g} | "
                         f"{r['energy_wh']:g} | {r['usable_wh']:g} | {res} |")
        lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    firsts = [recommend(c[2])[0][0]["code"] if recommend(c[2])[0] else None for c in CASES]
    print("first eligible per case:", firsts)
    print("stations never first:", sorted({s["code"] for s in STATIONS} - set(firsts)))


if __name__ == "__main__":
    main()
